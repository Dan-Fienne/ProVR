import {SurfaceRepresentation} from './SurfaceRepresentation.js';

export function registerSurfaceRepresentation(registryOrManager) {
    registryOrManager.register('surface', {
        factory: ({spec, context}) => new SurfaceRepresentation({spec, context}),
        family: 'surface',
        capabilities: {
            pickAtom: false,
            pickBond: false,
            pickResidue: true,
            pickResidueRange: true,
            pickChain: true,
            supportsIncrementalAtomUpdate: false,
            rendersThreeObjects: true,
            supportsRangeScopedSurface: true,
            supportsLayeredSurface: true,
            supportsSurfaceLayerRigidInspectionDrag: true,
            supportsNoRebuildDuringRigidDrag: true,
            supportsFullComplexSurface: true,
            supportsChainSurface: true,
            supportsMultiChainSurface: true,
            supportsMultipleColoredRanges: true,
            supportsResidueNumberColorRules: true,
            storesVertexAtomOwnership: true,
            storesVertexResidueOwnership: true,
            visualMeshPickableByDefault: true,
            dragResolvesToResidueRange: true,
            inspectionDragDoesNotModifyProteinModel: true,
            surfaceLayerContactAnalysis: true,
            transformAwareSurfaceLayerContactAnalysis: true,
        },
        defaults: {
            filter: {
                protein: true,
                nucleic: true,
                heterogen: false,
                water: false,
                unknown: false,
            },
            layers: [],
            ranges: [],
            residueColorRules: [],
            style: {
                colorMode: 'range',
                opacity: 0.46,
                roughness: 0.42,
                metalness: 0.0,
                side: 'double',
                wireframe: false,
                probeRadius: 1.40,
                gridSpacing: 0.80,
                surfaceRadiusScale: 1.0,
                bboxPadding: 2.4,
                maxGridPoints: 220000,
                maxAtomsPerRange: 2400,
                contactThreshold: 1.2,
                clashThreshold: 0.35,
                maxContactSamplesPerLayer: 1000,
                minRangeResidues: 1,
                livePreview: false,
                rebuildOnRigidTransform: false,
            },
            geometry: {livePreview: false},
            interaction: {
                pickable: true,
                visualMeshPickable: true,
                targetLevel: 'residueRange',
            },
        },
    });
}
