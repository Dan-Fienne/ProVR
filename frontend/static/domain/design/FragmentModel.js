export class FragmentAnchor {
    constructor({residueId = null, atomIds = [], role = 'anchor', metadata = {}} = {}) {
        this.residueId = residueId;
        this.atomIds = [...atomIds];
        this.role = role;
        this.metadata = {...metadata};
    }
}

export class FragmentModel {
    constructor({
                    id,
                    name = '',
                    kind = 'fragment',
                    residueIds = [],
                    atomIds = [],
                    anchors = {},
                    metadata = {},
                } = {}) {
        if (!id) throw new Error('[FragmentModel] id is required');
        this.id = id;
        this.name = name || id;
        this.kind = kind;
        this.residueIds = [...residueIds];
        this.atomIds = [...atomIds];
        this.anchors = {
            nTerm: anchors.nTerm ? new FragmentAnchor(anchors.nTerm) : null,
            cTerm: anchors.cTerm ? new FragmentAnchor(anchors.cTerm) : null,
        };
        this.metadata = {...metadata};
    }

    toJSON() {
        return {
            id: this.id,
            name: this.name,
            kind: this.kind,
            residueIds: [...this.residueIds],
            atomIds: [...this.atomIds],
            anchors: {
                nTerm: this.anchors.nTerm ? {...this.anchors.nTerm} : null,
                cTerm: this.anchors.cTerm ? {...this.anchors.cTerm} : null,
            },
            metadata: {...this.metadata},
        };
    }
}

export class FragmentLibrary {
    constructor() {
        this.fragments = new Map();
        this._registerBuiltins();
    }

    register(fragment) {
        const model = fragment instanceof FragmentModel ? fragment : new FragmentModel(fragment);
        this.fragments.set(model.id, model);
        return model;
    }

    get(id) {
        return this.fragments.get(id) || null;
    }

    first({kind = null} = {}) {
        for (const fragment of this.fragments.values()) {
            if (!kind || fragment.kind === kind) return fragment;
        }
        return null;
    }

    list() {
        return [...this.fragments.values()].map((f) => f.toJSON());
    }

    _registerBuiltins() {
        this.register({
            id: 'builtin_loop_6',
            name: 'Loop 6',
            kind: 'loop',
            metadata: {
                description: 'Placeholder six-residue loop fragment. Geometry is generated by future backend/fragment builder.',
                residueCount: 6,
            },
        });
        this.register({
            id: 'builtin_helix_8',
            name: 'Helix 8',
            kind: 'helix',
            metadata: {
                description: 'Placeholder eight-residue alpha helix fragment.',
                residueCount: 8,
            },
        });
        this.register({
            id: 'builtin_beta_hairpin',
            name: 'Beta hairpin',
            kind: 'sheet',
            metadata: {
                description: 'Placeholder beta hairpin fragment.',
                residueCount: 10,
            },
        });
    }
}
